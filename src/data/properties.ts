export function getPropertyById(id: string): Property | undefined {
  return PROPERTIES.find((p) => p.id === id);
}

export function getFilteredProperties(filters: {
  type?: string;
  bhk?: string;
  budgetMin?: number;
  budgetMax?: number;
  area?: string;
  furnished?: string;
}): Property[] {
  return PROPERTIES.filter((p) => {
    if (filters.type && p.type !== filters.type) return false;
    if (filters.bhk) {
      const bhkNum = parseInt(filters.bhk);
      if (bhkNum === 4) {
        if (p.bhk < 4) return false;
      } else {
        if (p.bhk !== bhkNum) return false;
      }
    }
    if (filters.budgetMin && p.price < filters.budgetMin) return false;
    if (filters.budgetMax && p.price > filters.budgetMax) return false;
    if (filters.area && p.area !== filters.area) return false;
    if (filters.furnished && p.furnished !== filters.furnished) return false;
    return true;
  });
}

export function getSimilarProperties(property: Property, limit = 3): Property[] {
  return PROPERTIES.filter(
    (p) => p.id !== property.id && (p.area === property.area || p.bhk === property.bhk)
  ).slice(0, limit);
}

